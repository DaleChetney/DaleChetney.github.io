import { describe, it, expect } from "vitest";
import {
  generatePermutationGroup,
  permutationFromCycles,
  permutationKey,
  type Permutation,
} from "../src/shared/mathUtils/groups/permutations.ts";
import type {
  CatalogueRepresentation,
  CatalogueSubgroupClass,
} from "../src/generatorVisualizer/groupCatalogue/catalogue.ts";
import { cycleRelabeling, relabelAlongOpeningClass } from "./relabelPoints.ts";

const cycles = (degree: number, ...cs: number[][]): Permutation =>
  permutationFromCycles(cs, degree);

const subgroupClass = (
  id: string,
  order: number,
  cyclic: boolean,
  covers: number[] = [],
): CatalogueSubgroupClass => ({
  id,
  order,
  count: 1,
  cyclic,
  normal: true,
  texName: id,
  displayName: id,
  covers,
});

describe("cycleRelabeling", () => {
  it("numbers a full cycle's points in the order it visits them", () => {
    const relabeling = cycleRelabeling(cycles(4, [1, 3, 2, 4]));
    // 1 → 1, 3 → 2, 2 → 3, 4 → 4
    expect(relabeling).toEqual([1, 3, 2, 4]);
  });

  it("takes each cycle from its smallest unplaced point, fixed points last", () => {
    const relabeling = cycleRelabeling(cycles(6, [2, 5], [3, 6, 4]));
    // 2 → 1, 5 → 2, 3 → 3, 6 → 4, 4 → 5, then the fixed 1 → 6
    expect(relabeling).toEqual([6, 1, 3, 5, 2, 4]);
  });

  it("leaves the identity alone", () => {
    expect(cycleRelabeling([1, 2, 3])).toEqual([1, 2, 3]);
  });
});

describe("relabelAlongOpeningClass", () => {
  // C6 acting regularly, generated by a scrambled 6-cycle, with the C2 and C3
  // classes listed before the C6 the page opens on.
  const scrambled = cycles(6, [1, 4, 2, 6, 3, 5]);
  const power = (p: Permutation, k: number): Permutation =>
    Array.from({ length: k - 1 }).reduce<Permutation>((acc) => acc.map((x) => p[x - 1]), p);
  const classes = [
    subgroupClass("1.a1", 1, true),
    subgroupClass("3.a1", 2, true, [0]),
    subgroupClass("2.a1", 3, true, [0]),
    subgroupClass("1.a1.a1", 6, true, [1, 2]),
  ];
  const representation: CatalogueRepresentation = {
    id: "6T1",
    title: "6T1",
    degree: 6,
    transitive: true,
    primitive: false,
    generators: [scrambled],
    classGenerators: [[], [power(scrambled, 3)], [power(scrambled, 2)], [scrambled]],
  };

  it("makes the opening class's generator walk the points in order", () => {
    const relabeled = relabelAlongOpeningClass(representation, classes);
    expect(relabeled.classGenerators[3]).toEqual([cycles(6, [1, 2, 3, 4, 5, 6])]);
  });

  it("renames every generator by the same relabeling", () => {
    const relabeled = relabelAlongOpeningClass(representation, classes);
    expect(relabeled.generators).toEqual([cycles(6, [1, 2, 3, 4, 5, 6])]);
    expect(relabeled.classGenerators[1]).toEqual([cycles(6, [1, 4], [2, 5], [3, 6])]);
    expect(relabeled.classGenerators[2]).toEqual([cycles(6, [1, 3, 5], [2, 4, 6])]);
    expect(relabeled.classGenerators[0]).toEqual([]);
  });

  it("opens on the last cyclic class, passing over a larger non-cyclic one", () => {
    // S3 on three points: the C3 is the last cyclic class, S3 itself is not.
    const rotation = cycles(3, [1, 3, 2]);
    const swap = cycles(3, [1, 2]);
    const s3: CatalogueRepresentation = {
      ...representation,
      id: "3T2",
      degree: 3,
      generators: [rotation, swap],
      classGenerators: [[], [swap], [rotation], [rotation, swap]],
    };
    const s3Classes = [
      subgroupClass("6.a1", 1, true),
      subgroupClass("3.a1", 2, true, [0]),
      subgroupClass("2.a1", 3, true, [0]),
      subgroupClass("1.a1", 6, false, [1, 2]),
    ];
    const relabeled = relabelAlongOpeningClass(s3, s3Classes);
    expect(relabeled.classGenerators[2]).toEqual([cycles(3, [1, 2, 3])]);
    const elements = (gens: readonly Permutation[]): string[] =>
      generatePermutationGroup(gens, 3).map(permutationKey).sort();
    expect(elements(relabeled.generators)).toEqual(elements(s3.generators));
  });

  it("leaves a representation with no nontrivial cyclic class unchanged", () => {
    const trivial: CatalogueRepresentation = {
      ...representation,
      degree: 1,
      generators: [[1]],
      classGenerators: [[]],
    };
    expect(relabelAlongOpeningClass(trivial, [subgroupClass("1.a1", 1, true)])).toEqual(trivial);
  });
});
