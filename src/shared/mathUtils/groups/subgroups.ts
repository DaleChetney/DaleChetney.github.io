import {
  composePermutations,
  generatePermutationGroup,
  invertPermutation,
  permutationOrder,
  type Permutation,
} from "./permutations";

/** A concrete subgroup: its elements, and their one-line forms as a lookup set. */
export interface Subgroup {
  elements: readonly Permutation[];
  keys: ReadonlySet<string>;
}

/**
 * A conjugacy class of subgroups. LMFDB stores subgroups at this granularity,
 * and the diagram draws one node per class.
 */
export interface SubgroupClass {
  /** Stable within a lattice: `<order>-<index among classes of that order>`. */
  id: string;
  order: number;
  /** Number of conjugate subgroups in the class. */
  count: number;
  cyclic: boolean;
  /**
   * Number of prime divisors of the order counted with multiplicity. LMFDB's
   * default subgroup diagram uses this, not the order, as the vertical axis.
   */
  level: number;
  /** A generator of `representative`, when the class is cyclic. */
  generator: Permutation | null;
  representative: Subgroup;
  conjugates: readonly Subgroup[];
}

export interface SubgroupLattice {
  classes: SubgroupClass[];
  /** `covers[i]` holds the indices of the classes immediately below class `i`. */
  covers: number[][];
}

const keyOf = (perm: Permutation): string => perm.join(",");

const identityKey = (subgroup: Subgroup): string => [...subgroup.keys].sort().join("|");

const subgroupOf = (generators: readonly Permutation[], degree: number): Subgroup => {
  const elements = generatePermutationGroup(generators, degree);
  return { elements, keys: new Set(elements.map(keyOf)) };
};

/** Number of prime divisors of `n` counted with multiplicity. */
export const primeDivisorCount = (n: number): number => {
  let remaining = n;
  let count = 0;
  for (let factor = 2; factor * factor <= remaining; factor++) {
    while (remaining % factor === 0) {
      remaining /= factor;
      count++;
    }
  }
  return remaining > 1 ? count + 1 : count;
};

const conjugate = (subgroup: Subgroup, by: Permutation): Subgroup => {
  const inverse = invertPermutation(by);
  const elements = subgroup.elements.map((element) =>
    composePermutations(composePermutations(by, element), inverse),
  );
  return { elements, keys: new Set(elements.map(keyOf)) };
};

const isSubsetOf = (a: Subgroup, b: Subgroup): boolean => {
  if (a.elements.length > b.elements.length) return false;
  for (const key of a.keys) if (!b.keys.has(key)) return false;
  return true;
};

/**
 * Every subgroup, found by closing the cyclic subgroups under pairwise join.
 * Every subgroup is generated by its elements, so it is the join of the cyclic
 * subgroups it contains, and this reaches all of them.
 */
const allSubgroups = (elements: readonly Permutation[], degree: number): Subgroup[] => {
  const cyclic = new Map<string, Subgroup>();
  for (const element of elements) {
    const subgroup = subgroupOf([element], degree);
    cyclic.set(identityKey(subgroup), subgroup);
  }

  const found = new Map(cyclic);
  let frontier = [...found.values()];
  while (frontier.length > 0) {
    const next: Subgroup[] = [];
    for (const a of frontier) {
      for (const b of cyclic.values()) {
        if (isSubsetOf(b, a)) continue;
        const joined = subgroupOf([...a.elements, ...b.elements], degree);
        const key = identityKey(joined);
        if (found.has(key)) continue;
        found.set(key, joined);
        next.push(joined);
      }
    }
    frontier = next;
  }
  return [...found.values()];
};

/**
 * The lattice of subgroups up to conjugacy, with cover relations, ordered by
 * subgroup order ascending so the trivial subgroup is first and the whole group
 * last.
 */
export const computeSubgroupLattice = (
  generators: readonly Permutation[],
  degree: number,
): SubgroupLattice => {
  const elements = generatePermutationGroup(generators, degree);
  const subgroups = allSubgroups(elements, degree);

  const seen = new Set<string>();
  const grouped: Subgroup[][] = [];
  for (const subgroup of subgroups) {
    if (seen.has(identityKey(subgroup))) continue;
    const conjugates: Subgroup[] = [];
    const local = new Set<string>();
    for (const element of elements) {
      const image = conjugate(subgroup, element);
      const key = identityKey(image);
      if (local.has(key)) continue;
      local.add(key);
      seen.add(key);
      conjugates.push(image);
    }
    grouped.push(conjugates);
  }

  grouped.sort((a, b) => a[0].elements.length - b[0].elements.length);

  const perOrder = new Map<number, number>();
  const classes: SubgroupClass[] = grouped.map((conjugates) => {
    const representative = conjugates[0];
    const order = representative.elements.length;
    const index = perOrder.get(order) ?? 0;
    perOrder.set(order, index + 1);
    const generator =
      representative.elements.find((element) => permutationOrder(element) === order) ?? null;
    return {
      id: `${order}-${index}`,
      order,
      count: conjugates.length,
      cyclic: generator !== null,
      level: primeDivisorCount(order),
      generator,
      representative,
      conjugates,
    };
  });

  // A class sits below another when some conjugate of the first lies inside some
  // conjugate of the second; covers are that relation's transitive reduction.
  const below = classes.map((lower) =>
    classes.map(
      (upper) =>
        lower !== upper &&
        lower.conjugates.some((a) => upper.conjugates.some((b) => isSubsetOf(a, b))),
    ),
  );
  const covers = classes.map((_, upper) =>
    classes
      .map((__, lower) => lower)
      .filter(
        (lower) =>
          below[lower][upper] &&
          !classes.some((___, middle) => below[lower][middle] && below[middle][upper]),
      ),
  );

  return { classes, covers };
};

/** One element that generates a subgroup in a class, and which conjugate it generates. */
export interface GeneratorElement {
  permutation: Permutation;
  /** Index into the class's `conjugates`. */
  conjugate: number;
}

export interface GeneratorChoices {
  elements: GeneratorElement[];
  /** How many there were before `limit` was applied. */
  total: number;
}

/**
 * The elements that generate the subgroups in a class: those whose order equals
 * the subgroup order. Two conjugates never share one, since an element
 * determines the cyclic subgroup it generates, so each element names exactly one
 * conjugate -- which is what makes it possible to pick two generators of the
 * same class that together generate more than either does alone.
 *
 * Ordered by conjugate, then by the element's one-line form, so the listing is
 * stable; `limit` caps how many are returned, not how many are counted.
 */
export const generatorElements = (
  subgroupClass: SubgroupClass,
  limit: number,
): GeneratorChoices => {
  const elements: GeneratorElement[] = [];
  subgroupClass.conjugates.forEach((conjugate, index) => {
    const generators = conjugate.elements
      .filter((element) => permutationOrder(element) === subgroupClass.order)
      .sort((a, b) => keyOf(a).localeCompare(keyOf(b)));
    for (const permutation of generators) {
      elements.push({ permutation, conjugate: index });
    }
  });
  return { elements: elements.slice(0, limit), total: elements.length };
};

/** Whether `generators` generate the whole group of order `order`. */
export const generatesWholeGroup = (
  generators: readonly Permutation[],
  degree: number,
  order: number,
): boolean =>
  generators.length > 0 && generatePermutationGroup(generators, degree).length === order;
